# | shelf | col1 | col2 | col3 | col4 |
# |---|---|---|---|---|
# | R1 | 11 | 12 | 13 | 14 |
# | R2 | 21 | 22 | 23 | 24 |
# | R3 | 31 | 32 | 33 | 34 |
# | R4 | 41 | 42 | 43 | 44 |
# 建议先做练习，再逐段对照下面的实现；assert 用于验证结果。

import numpy as np
a = np.array([[11,12,13,14],[21,22,23,24],[31,32,33,34],[41,42,43,44]])
print('\n===== a[:, -1] =====')
print(a[:, -1])
print('\n===== a[-1:, :] =====')
print(a[-1:, :])
print('\n===== a[1::2, ::2] =====')
print(a[1::2, ::2])
print('\n===== a[::-1, :] =====')
print(a[::-1, :])
assert a[:, -1].tolist() == [14, 24, 34, 44]
assert a[-1:, :].shape == (1, 4)
assert a[1::2, ::2].tolist() == [[21,23],[41,43]]
assert np.array_equal(a[::-1, :][0], a[-1])
# 人类编号从1开始，NumPy索引从0开始，所以偶数编号行从索引1开始。
