"""案例驱动示例：提取学生、科目与保持维度"""
# 对应 PDF：11-numpy-full.pdf 第 5—8、63—66 页
# 任务：取出第三列，以及第一名学生的二维子表。
# 坐标从0开始；使用单个整数与一个范围，结果维度不同。
# 案例数据：
# | 学生 | Python | 数学 | 英语 |
# |---|---:|---:|---:|
# | A | 80 | 70 | 90 |
# | B | 60 | 85 | 75 |
# | C | 90 | 65 | 80 |
# 先看整体路线：
# 第 1 步：按行列坐标读取单值。
# 第 2 步：练习省略边界、步长和倒序。
# 第 3 步：比较整数索引与切片的形状。

import numpy as np
scores = np.array([[80,70,90],[60,85,75],[90,65,80]])
# [行,列]；: 表示这个轴全部保留。
print('\n===== scores[0, 2] =====')
print(scores[0, 2])
print('\n===== scores[:, 2] =====')
print(scores[:, 2])
print('\n===== scores[:2, 1:] =====')
print(scores[:2, 1:])
print('\n===== scores[::2, 1::2] =====')
print(scores[::2, 1::2])
print('\n===== scores[::-1] =====')
print(scores[::-1])
# 单个整数选中并移除一根轴；0:1 选择一段范围，仍保留轴。
row = scores[0, :]
table = scores[0:1, :]
print('\n===== (row, row.shape) =====')
print((row, row.shape))
print('\n===== (table, table.shape) =====')
print((table, table.shape))
print('\n===== scores[:, 2:3] =====')
print(scores[:, 2:3])
assert row.shape == (3,) and table.shape == (1,3)
assert scores[:,2].tolist() == [90,75,80]
