"""案例驱动示例：找出达标成绩和达标学生"""
# 对应 PDF：11-numpy-full.pdf 第 11—12 页
# 任务：找出80到90分（含边界）的单项成绩，再找所有科目都及格的学生。
# 布尔掩码像一张选票，每个 True 对应要保留的位置。
# 案例数据：
# | 学生 | Python | 数学 |
# |---|---:|---:|
# | A | 80 | 90 |
# | B | 60 | 85 |
# | C | 95 | 55 |
# 先看整体路线：
# 第 1 步：先用循环完成区间筛选。
# 第 2 步：展示比较、并且、或者、取反。
# 第 3 步：区分元素掩码与行掩码，使用 all/any。

import numpy as np
a = np.array([[80,90],[60,85],[95,55]])
manual = [v for row in a for v in row if 80 <= v <= 90]
print('\n===== manual =====')
print(manual)
mask = (a >= 80) & (a <= 90)
print('\n===== mask =====')
print(mask)
print('\n===== a[mask] =====')
print(a[mask])
# | 是逐元素“或”，~ 是布尔取反；不能用 Python 的 and/or 代替。
print('\n===== a[(a < 60) | (a > 90)] =====')
print(a[(a < 60) | (a > 90)])
print('\n===== a[~(a >= 60)] =====')
print(a[~(a >= 60)])
# 二维元素掩码选出的是一维元素集合；要保留学生整行，先沿列轴汇总。
passed = (a >= 60).all(axis=1)
print('\n===== passed =====')
print(passed)
print('\n===== a[passed] =====')
print(a[passed])
print('\n===== a[(a >= 90).any(axis=1)] =====')
print(a[(a >= 90).any(axis=1)])
assert a[mask].tolist() == [80,90,85]
assert a[passed].shape == (2,2)

