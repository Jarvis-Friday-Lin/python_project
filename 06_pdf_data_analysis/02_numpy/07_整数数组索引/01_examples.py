"""案例驱动示例：每人选择不同科目的成绩"""
# 对应 PDF：11-numpy-full.pdf 第 9—10 页
# 任务：A选英语、B选Python、C选数学。
# 切片适合规则区间，这次每行所选列不同，需要一组坐标。
# 案例数据：
# | 学生 | Python(0) | 数学(1) | 英语(2) | 所选列 |
# |---|---:|---:|---:|---:|
# | A | 80 | 70 | 90 | 2 |
# | B | 60 | 85 | 75 | 0 |
# | C | 90 | 65 | 80 | 1 |
# 先看整体路线：
# 第 1 步：先循环按每人的列号取分。
# 第 2 步：用行坐标数组与列坐标数组配对索引。
# 第 3 步：比较配对选择与矩形选择，再展示原位修改。

import numpy as np
scores = np.array([[80,70,90],[60,85,75],[90,65,80]])
columns = np.array([2,0,1])
manual = [scores[i, columns[i]] for i in range(3)]
print('\n===== manual =====')
print(manual)
rows = np.arange(3)
# 两个等长索引逐项配对：(0,2)、(1,0)、(2,1)，不是取所有行列组合。
chosen = scores[rows, columns]
print('\n===== chosen =====')
print(chosen)
print('\n===== scores[[0,0], [2,2]] =====')
print(scores[[0,0], [2,2]])
# np.ix_ 把两个一维索引扩展为可广播的网格，得到矩形子表。
print('\n===== scores[np.ix_([0,2],[0,2])] =====')
print(scores[np.ix_([0,2],[0,2])])
# 整数高级索引的读取结果是副本；直接通过原数组的索引赋值才会更新原表。
chosen[0] = 0
print('\n===== scores[0,2] =====')
print(scores[0,2])
scores[rows, columns] += 5
print('\n===== scores =====')
print(scores)
assert manual == [90,60,65]
assert scores[0,2] == 95

